from typing import TypedDict, List, Dict, Any

from app.schemas.research import ResearchQuestion, ResearchPlan
from app.schemas.source import Source
from app.schemas.evidence import Evidence, Finding


class ResearchState(TypedDict, total=False):
    question: ResearchQuestion

    research_plan: ResearchPlan

    search_queries: List[str]
    pending_queries: List[str]

    sources: List[Source]

    # Notes the user pasted in (Google reviews, Instagram observations ...).
    # LangGraph drops keys that are not declared here, so this must exist.
    manual_evidence: List[Dict[str, Any]]

    evidence: List[Evidence]

    contradictions: List[Dict[str, Any]]

    # Raw findings generated by the LLM.
    findings: List[Finding]

    # Findings that passed the verification step.
    verified_findings: List[Finding]

    insights: List[str]

    missing_information: List[str]

    evidence_score: float

    iteration: int
    max_iterations: int

    quality_decision: str

    report: str

    # Label used for the files written to research/.
    run_id: str
