from typing import List

from pydantic import BaseModel, Field


class ResearchQuestion(BaseModel):
    """
    Represents the user's original research question.
    """

    question: str = Field(..., min_length=1)

    depth: str = Field(
        default="deep"
    )

    max_iterations: int = Field(
        default=3,
        ge=1,
    )


class ResearchQuery(BaseModel):
    """
    Represents one search query generated by the research planner.
    """

    query: str = Field(..., min_length=1)

    purpose: str = Field(..., min_length=1)

    priority: int = Field(
        default=3,
        ge=1,
        le=5,
    )


class ResearchPlan(BaseModel):
    """
    Structured research plan produced by the planner.
    """

    queries: List[ResearchQuery]

    research_goals: List[str] = Field(
        default_factory=list
    )

    expected_output: str = Field(
        default="Evidence-backed research findings"
    )